interface ProductInput {
  id: string
  name: string
  brand: string
  categoryId: string
  sellerId: string
  price: number
  listPrice?: number
  condition: Condition
  year?: number | null
  stock?: number
  freeShipping?: boolean
  rating: number
  reviewCount: number
  sponsored?: boolean
  description?: string
  specs?: ProductSpec[]
  variants?: VariantGroup[]
}

function defineProduct(input: ProductInput): ProductFixture {
  // A credited photo when Commons has a good free one; the generated placeholder otherwise.
  const imageUrl = photoCredits[input.id] ? `/img/photos/${input.id}.webp` : `/img/products/${input.id}.svg`
  const baseSpecs: ProductSpec[] = [
    { label: 'Marca', value: input.brand },
    ...(input.year ? [{ label: 'Ano', value: String(input.year) }] : []),
    { label: 'Condição', value: conditionSpec[input.condition] },
  ]
  return Object.freeze({
    id: input.id,
    slug: slugify(input.name),
    name: input.name,
    brand: input.brand,
    categoryId: input.categoryId,
    sellerId: input.sellerId,
    price: input.price,
    listPrice: input.listPrice ?? null,
    condition: input.condition,
    year: input.year ?? null,
    stock: input.variants ? null : (input.stock ?? 0),
    freeShipping: input.freeShipping ?? false,
    imageUrl,
    images: Object.freeze([imageUrl]),
    rating: input.rating,
    reviewCount: input.reviewCount,
    listedAt: listedAtFor(input.id),
    sponsored: input.sponsored ?? false,
    description:
      input.description ??
      `${input.name}, da ${input.brand}. ${conditionSentence[input.condition]} Enviado com embalagem reforçada e nota fiscal.`,
    specs: Object.freeze([
      ...baseSpecs,
      ...(input.specs ?? categorySpecs[input.categoryId]?.(input) ?? []),
    ]),
    ...(input.variants ? { variants: Object.freeze(input.variants) } : {}),
  })
}

