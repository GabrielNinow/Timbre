export const LISTING_EPOCH = '2026-08-10T12:00:00Z'

const DAY_MS = 86_400_000

function listedAtFor(id: string): string {
  const n = Number(id.slice(2))
  const daysAgo = ((n * 37) % 180) + 1
  return new Date(Date.parse(LISTING_EPOCH) - daysAgo * DAY_MS).toISOString().replace('.000Z', 'Z')
}

export function slugify(value: string): string {
  return value
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

